// 独立 userData 的 Electron dev；真实后台命令，不模拟设置通道，不登录或播放。
// NODE_PATH 指向 Playwright，CDP_URL 可覆盖；首次正常运行，退出重启同一profile后以 PHASE=restart 复验。
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.connectOverCDP(process.env.CDP_URL || 'http://127.0.0.1:9478')
 const pages=browser.contexts()[0].pages()
 const page=pages.find(p=>p.url().endsWith('/index.html'))
 const host=pages.find(p=>p.url().endsWith('/playback-host.html'))
 page.setDefaultTimeout(10000)
 await page.evaluate(async()=>{window.__exploreSmokeSettings=(await import('/src/stores/settings.ts')).useSettingsStore})
 await host.evaluate(async()=>{window.__exploreSmokeSettings=(await import('/src/stores/settings.ts')).useSettingsStore})
 const read=target=>target.evaluate(async()=>{const{useSettingsStore:s}=await import('/src/stores/settings.ts');return s.getState().exploreLayouts.qishui})
 const expected=[{id:'saved',enabled:true},{id:'listening',enabled:false}]
 if(process.env.PHASE==='restart'){
  assert.deepEqual(await read(host),expected)
  assert.deepEqual(await read(page),expected)
  console.log('冷启动后后台与主窗口配置一致，开关及排序均保留')
 }else{
  await page.keyboard.press('Escape');await page.waitForTimeout(250)
  await page.evaluate(async()=>{const{useProviderStore:p}=await import('/src/stores/providers.ts');const{useNavigationStore:n}=await import('/src/stores/navigation.ts');const{useSettingsStore:s}=await import('/src/stores/settings.ts');await s.getState().setExploreLayout('qishui',[]);await p.getState().setEnabled('qishui',true);await n.getState().navigateTo('settings')})
  await page.waitForFunction(()=>document.querySelectorAll('button[aria-label="汽水音乐设置"]').length===1)
  const gear=page.getByRole('button',{name:'汽水音乐设置',exact:true})
  await gear.scrollIntoViewIfNeeded();await gear.click()
  const panel=page.getByRole('dialog',{name:'汽水音乐设置',exact:true})
  await panel.waitFor()
  await panel.getByRole('switch',{name:'展示继续听',exact:true}).click()
  await page.waitForFunction(()=>window.__exploreSmokeSettings.getState().exploreLayouts.qishui.find(m=>m.id==='listening').enabled===false)
  const rows=panel.locator('[data-reorder-row]')
  const from=await rows.nth(1).boundingBox();const to=await rows.nth(0).boundingBox()
  await page.mouse.move(from.x+18,from.y+from.height/2);await page.mouse.down();await page.mouse.move(to.x+18,to.y+8,{steps:15});await page.mouse.up()
  await page.waitForFunction(()=>window.__exploreSmokeSettings.getState().exploreLayouts.qishui[0].id==='saved')
  await host.waitForFunction(()=>window.__exploreSmokeSettings.getState().exploreLayouts.qishui[0].id==='saved')
  assert.deepEqual(await read(host),expected)
  const persisted=await host.evaluate(()=>JSON.parse(localStorage.getItem('simplemusic-settings')).exploreLayouts.qishui)
  assert.deepEqual(persisted,expected)
  await page.reload();await page.waitForLoadState('domcontentloaded');await page.evaluate(async()=>{window.__exploreSmokeSettings=(await import('/src/stores/settings.ts')).useSettingsStore})
  await page.waitForFunction(()=>window.__exploreSmokeSettings.getState().exploreLayouts.qishui[0].id==='saved')
  assert.deepEqual(await read(page),expected)
  fs.writeFileSync(process.env.RESULT_PATH || 'docs/reviews/assets/2026-11-06-explore-preview/persistence.json',JSON.stringify({environment:'独立userData macOS Electron dev，真实主窗口→后台命令与存档，无mock账号/设置通道；仅启用汽水游客本地内容，不登录或播放',checks:['真实鼠标关闭继续听','真实拖动调整排序','后台快照与存档一致','主窗口重载后配置保留'],expected},null,2))
  console.log('主窗口命令、后台保存、快照回传及主窗口重载均通过')
 }
 await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
